#!/usr/bin/env python3
# agentive-unit: gen.design
# design: decisions.accepted[DESIGNINDEX], spec.framework_repo (design/framework.yaml stays one file)
"""Find and read one node of design/framework.yaml without opening the whole 900 KB file.

  python3 tools/design.py get <path> [--max-chars N]   print one node as YAML (default cap 6000 characters, 0 = no cap)
  python3 tools/design.py find <text> [--limit N]      list the indexed entries whose text holds <text>, with their line
  python3 tools/design.py index                        print design/INDEX.md as the generator would write it

<path> is the dotted path the units use: `spec.guard`, `decisions.accepted[PRADOPT]`, `spec.repo_layer.files[f-pr]`,
`spec.review_pipeline.stages[RV5]`, `unverified[UV-13]`, `contracts[manifest]`; [id] picks the list item whose id is id.

design/INDEX.md is GENERATED by tools/generate.py (never edit it; `generate.py --check` reports it STALE after a design edit).
Its line numbers come from the YAML parser at generation time, so they are never written by hand.
"""
import argparse
import os
import re
import sys

try:
    import yaml
except ImportError as e:  # dev-time dependency of the framework repo only
    print(f"ERROR tools/design.py: missing dev dependency ({e.name}). NEXT: python3 -m pip install -r requirements-dev.txt")
    sys.exit(2)

# libyaml (C) loader and dumper when PyYAML was built with them, else the pure Python ones: same data, about 12 times faster on
# the 1 MB design file [설계 판단]. Dev-time tools only; the installed runtime never imports PyYAML.
SafeLoader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
SafeDumper = getattr(yaml, "CSafeDumper", yaml.SafeDumper)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = "design/framework.yaml"
INDEX = "design/INDEX.md"
DEFAULT_CAP = 6000
# lists of id-bearing items that are indexed one by one (everything else is found with `find` or grep)
ITEM_LISTS = ["contracts", "unverified", "decisions.accepted", "decisions.decided", "decisions.defaults", "decisions.probes",
              "decisions.resolved", "decisions.removed", "spec.repo_layer.files", "spec.review_pipeline.stages"]


def design_lookup(design, ref):
    """Resolve `a.b[c].d` in design/framework.yaml; [c] picks the list item whose id is c (or the dict key c)."""
    node = design
    for part in re.findall(r"[^.\[\]]+|\[[^\]]+\]", ref):
        if part.startswith("["):
            key = part[1:-1]
            if isinstance(node, list):
                hit = [x for x in node if isinstance(x, dict) and str(x.get("id")) == key]
                if not hit:
                    return False, None
                node = hit[0]
            elif isinstance(node, dict) and key in node:
                node = node[key]
            else:
                return False, None
        else:
            if isinstance(node, dict) and part in node:
                node = node[part]
            else:
                return False, None
    return True, node


def _read(root, rel=DESIGN):
    with open(os.path.join(root, rel), encoding="utf-8") as f:
        return f.read()


def load(text):
    """yaml.safe_load with the fastest loader available."""
    return yaml.load(text, Loader=SafeLoader)


_TREES = {}   # parse tree of the design text, once per process: entries() and sources_range() read the same text


def _tree(text):
    if text not in _TREES:
        _TREES.clear()    # one design text at a time; a long-lived process that edits the file does not grow
        _TREES[text] = yaml.compose(text, Loader=SafeLoader)
    return _TREES[text]


def _map(node):
    """{key: (key node, value node)} of a mapping node."""
    return {k.value: (k, v) for k, v in node.value}


def _scalar(node, name):
    if isinstance(node, yaml.MappingNode):
        m = _map(node)
        if name in m and isinstance(m[name][1], yaml.ScalarNode):
            return m[name][1].value
    return ""


def _short(text, n=88):
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[:n - 3].rstrip() + "..."


def _walk(root_node, dotted):
    """The value node at a dotted path made of mapping keys only, or None."""
    node = root_node
    for part in dotted.split("."):
        if not isinstance(node, yaml.MappingNode):
            return None
        m = _map(node)
        if part not in m:
            return None
        node = m[part][1]
    return node


def _trim(lines, start, end):
    """Last content line (1-based) between start and end: trailing blank and comment-only lines are not part of an entry."""
    while end > start and (not lines[end - 1].strip() or lines[end - 1].lstrip().startswith("#")):
        end -= 1
    return end


def _spans(lines, starts, parent_end):
    """Entries start at `starts` (1-based, in file order); each ends before the next one starts, the last at the parent's end."""
    out = []
    for i, s in enumerate(starts):
        e = (starts[i + 1] - 1) if i + 1 < len(starts) else parent_end
        out.append((s, _trim(lines, s, e)))
    return out


def entries(root):
    """Every indexed node as a dict: {path, start, end, group, title}. Built from the YAML parse tree (real line numbers)."""
    text = _read(root)
    lines = text.split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    tree = _tree(text)
    out = []
    top = _map(tree)
    keys = list(top)
    spans = _spans(lines, [top[k][0].start_mark.line + 1 for k in keys], len(lines))
    top_span = {}
    for key, (s, e) in zip(keys, spans):
        top_span[key] = (s, e)
        v = top[key][1]
        out.append({"path": key, "start": s, "end": e, "group": "top", "title": _scalar(v, "title") or _scalar(v, "id")})
    sk = _map(top["spec"][1])
    skeys = list(sk)
    for key, (s, e) in zip(skeys, _spans(lines, [sk[k][0].start_mark.line + 1 for k in skeys], top_span["spec"][1])):
        out.append({"path": f"spec.{key}", "start": s, "end": e, "group": "spec", "title": _scalar(sk[key][1], "id")})
    for lst in ITEM_LISTS:
        node = _walk(tree, lst)
        if not isinstance(node, yaml.SequenceNode):
            continue
        items = [i for i in node.value if _scalar(i, "id")]
        starts = [i.start_mark.line + 1 for i in node.value]
        # an item's span runs to the line before the next item of the list (id-less items are not indexed but still end a span)
        parent_end = _trim(lines, starts[0], node.end_mark.line if node.end_mark.column == 0 else node.end_mark.line + 1)
        spans_ = dict(zip(starts, _spans(lines, starts, parent_end)))
        for item in items:
            ident = _scalar(item, "id")
            s, e = spans_[item.start_mark.line + 1]
            title = next((v for v in (_scalar(item, k) for k in ("title", "claim", "name", "role", "file", "path")) if v), "")
            out.append({"path": f"{lst}[{ident}]", "start": s, "end": e, "group": lst, "title": title})
    return out, text


def sources_range(root):
    tree = _tree(_read(root))
    node = _walk(tree, "sources")
    ids = [_scalar(i, "id") for i in node.value]
    return node.value[0].start_mark.line + 1, node.value[-1].start_mark.line + 1, ids


def render_index(root):
    ents, text = entries(root)
    total = text.count("\n") + 1
    s1, s2, sids = sources_range(root)
    out = ["<!-- Generated by tools/generate.py from design/framework.yaml. Do not edit: change the design and run python3 tools/generate.py. -->",
           "# design/framework.yaml index",
           "",
           f"`{DESIGN}` is one file of {total} lines; some lines are thousands of characters long, so open a node, not the file.",
           "Read one node: `python3 tools/design.py get <path>` (for example `get decisions.accepted[PRADOPT]`, `get spec.guard`;",
           "`--max-chars 0` removes the 6000 character cap). Search: `python3 tools/design.py find <text>` lists the entries that hold the text.",
           "A line number is where the entry starts in the file now: it is regenerated with the design, never edited by hand.",
           "",
           "## Top-level keys",
           "",
           "| key | lines | what |", "|---|---|---|"]
    for e in ents:
        if e["group"] == "top":
            out.append(f"| `{e['path']}` | {e['start']}-{e['end']} | {_short(e['title'])} |")
    out += ["", "## spec keys", "", "| path | lines | id |", "|---|---|---|"]
    for e in ents:
        if e["group"] == "spec":
            out.append(f"| `{e['path']}` | {e['start']}-{e['end']} | {e['title']} |")
    out += ["", "## Sources", "",
            f"`sources` has {len(sids)} one-line entries ({sids[0]} to {sids[-1]}) at lines {s1}-{s2}. Find one with "
            f"`grep -n \"id: S146\" {DESIGN}` or `python3 tools/design.py get sources[S146]`.", ""]
    titles = {"contracts": "Contracts (file -> schema -> writer/reader)", "unverified": "Unverified claims (UV ids)",
              "decisions.accepted": "Accepted design decisions", "decisions.decided": "Decided user choices",
              "decisions.defaults": "Defaults and constants", "decisions.probes": "Probes",
              "decisions.resolved": "Resolved (obsolete) items", "decisions.removed": "Removed by the user (never reintroduce)",
              "spec.repo_layer.files": "Installed files (spec.repo_layer.files, ids f-*)",
              "spec.review_pipeline.stages": "Review pipeline stages (RV*)"}
    for lst in ITEM_LISTS:
        rows = [e for e in ents if e["group"] == lst]
        out += [f"## {titles[lst]} ({len(rows)})", "", f"| `{lst}[id]` | line | what |", "|---|---|---|"]
        for e in rows:
            ident = e["path"][len(lst) + 1:-1]
            out.append(f"| `{ident}` | {e['start']} | {_short(e['title']).replace('|', '/')} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def cmd_get(root, path, max_chars):
    design = load(_read(root))
    ok, node = design_lookup(design, path)
    if not ok:
        print(f"ERROR design.py: no node {path!r}. NEXT: look the id up in {INDEX} or run `python3 tools/design.py find <text>`")
        return 1
    if isinstance(node, (dict, list)):
        text = yaml.dump(node, Dumper=SafeDumper, allow_unicode=True, sort_keys=False, width=100000, default_flow_style=False)
    else:
        text = str(node)
    if max_chars and len(text) > max_chars:
        print(text[:max_chars].rstrip())
        print(f"... [cut at {max_chars} of {len(text)} characters]. NEXT: a deeper path (for example {path}.<key>) or --max-chars 0")
    else:
        print(text.rstrip())
    return 0


def cmd_find(root, needle, limit):
    ents, text = entries(root)
    lines = text.split("\n")
    hits = []
    # innermost indexed entry that holds the text: later entries of the same list are narrower than their list's parent keys
    for e in sorted((x for x in ents if x["group"] not in ("top",)), key=lambda x: x["end"] - x["start"]):
        body = "\n".join(lines[e["start"] - 1:e["end"]])
        if needle.lower() in body.lower():
            hits.append(e)
    shown = hits[:limit]
    for e in shown:
        print(f"{e['path']}\tline {e['start']}\t{_short(e['title'], 70)}")
    if not hits:
        print(f"design.py find: nothing holds {needle!r}. NEXT: try a shorter text or grep -n {DESIGN}")
        return 1
    if len(hits) > len(shown):
        print(f"... {len(hits) - len(shown)} more. NEXT: a longer text or --limit {len(hits)}")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="read one node of design/framework.yaml")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("get")
    g.add_argument("path")
    g.add_argument("--max-chars", type=int, default=DEFAULT_CAP)
    f = sub.add_parser("find")
    f.add_argument("text")
    f.add_argument("--limit", type=int, default=25)
    sub.add_parser("index")
    ap.add_argument("--root", default=ROOT, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    if a.cmd == "get":
        return cmd_get(a.root, a.path, a.max_chars)
    if a.cmd == "find":
        return cmd_find(a.root, a.text, a.limit)
    sys.stdout.write(render_index(a.root))
    return 0


if __name__ == "__main__":
    sys.exit(main())
